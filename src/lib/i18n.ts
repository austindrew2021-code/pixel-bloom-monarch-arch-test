const DICT: Record<LocaleId, Record<string, string>> = { en: EN, fr: FR, es: ES };

export function t(locale: LocaleId, key: string): string {
  return DICT[locale]?.[key] ?? EN[key] ?? key;
}

export function voiceFor(locale: LocaleId): string {
  return LOCALES.find((l) => l.id === locale)?.voice ?? "en-CA";
}

export function htmlLang(locale: LocaleId): string {
  if (locale === "fr") return "fr";
  if (locale === "es") return "es";
  return "en";
}
