#!/usr/bin/env node
/**
 * Writes the list of dish photos that actually exist on disk.
 *
 * `public/` is copied verbatim by Vite, so nothing in the bundle can see inside
 * it — which is why the photo map used to be typed out by hand, and why it
 * drifted: 655 files were sitting in public/food and only 250 were ever wired
 * up. 234 dishes had a photograph of themselves that the app never showed.
 *
 * Generating the list from the directory means dropping a correctly-named file
 * in is the whole job. `npm run photos` regenerates; a test fails if the
 * manifest and the directory disagree, so a photo added without regenerating
 * gets caught rather than silently ignored.
 */
import { readdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FOOD_DIR = join(ROOT, "public/food");
const OUT = join(ROOT, "src/lib/generated/food-photo-files.ts");

/** Basenames (no extension) of every dish photo, with the extension we found. */
export function readPhotoFiles(dir = FOOD_DIR) {
  if (!existsSync(dir)) return {};
  /** @type {Record<string, string>} */
  const out = {};
  for (const file of readdirSync(dir).sort()) {
    const match = /^(.+)\.(jpg|jpeg|png|webp|avif)$/i.exec(file);
    if (!match) continue;
    const [, base, ext] = match;
    // A .webp beside a .jpg wins: same picture, fewer bytes on a phone.
    const better = /webp|avif/i.test(ext);
    if (!out[base] || better) out[base] = file;
  }
  return out;
}

/** @param {Record<string, string>} files */
export function renderManifest(files) {
  const entries = Object.entries(files)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([base, file]) => `  ${JSON.stringify(base)}: ${JSON.stringify(file)},`)
    .join("\n");
  return `// GENERATED by scripts/food-photo-manifest.mjs — do not edit.
// Run \`npm run photos\` after adding or removing a file in public/food.
//
// Keys are dish ids (and the plate fallbacks); values are the file in
// public/food that holds that dish's photograph.

export const FOOD_PHOTO_FILES: Record<string, string> = {
${entries}
};

export const FOOD_PHOTO_COUNT = ${Object.keys(files).length};
`;
}

const files = readPhotoFiles();
const next = renderManifest(files);
const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (prev !== next) {
  writeFileSync(OUT, next);
  console.log(`[photos] wrote ${Object.keys(files).length} entries to src/lib/generated/food-photo-files.ts`);
} else {
  console.log(`[photos] up to date — ${Object.keys(files).length} entries`);
}
